// Turn the workspace manifests into the build facts the site publishes.
//
//   npm run generate
//
// Writes site/generated/build.json: the release the site was built from, the
// upstream versions it is built against, and where the source lives. A visitor
// deciding whether to depend on this needs the versions, because gpui-ai,
// gpui-component, and GPUI itself are one compatible set and mixing them is
// how you end up with two copies of GPUI's types.
//
// Deliberately free of timestamps and of anything else that changes without the
// inputs changing: CI regenerates this file and fails on a diff.

import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = process.env.GPUI_AI_SOURCE_ROOT ?? fileURLToPath(new URL("..", import.meta.url));
const OUTPUT = join(process.env.GPUI_AI_OUTPUT_ROOT ?? ROOT, "site", "generated");

/** Reads one `key = "value"` from a TOML file, without a TOML parser. */
function field(toml, key) {
  const match = new RegExp(`^${key} = "([^"]+)"`, "m").exec(toml);
  if (!match) throw new Error(`${key} is missing from the manifest`);
  return match[1];
}

/** The version Cargo.lock resolved a dependency to. */
function lockedVersion(lock, crate) {
  const match = new RegExp(`\\[\\[package\\]\\]\\nname = "${crate}"\\nversion = "([^"]+)"`).exec(lock);
  if (!match) throw new Error(`Cargo.lock has no resolved version for ${crate}`);
  return match[1];
}

const workspace = readFileSync(join(ROOT, "Cargo.toml"), "utf8");
const crate = readFileSync(join(ROOT, "crates", "gpui-ai", "Cargo.toml"), "utf8");
const lock = readFileSync(join(ROOT, "Cargo.lock"), "utf8");

/**
 * The feature list on the workspace's `gpui_platform` dependency.
 *
 * Parsed rather than imported because there is no TOML reader here and this is
 * one array in one manifest; a wrong answer fails loudly below rather than
 * publishing a shorter list.
 */
function platformFeatures(manifest) {
  const declared = /gpui_platform\s*=\s*\{[^}]*features\s*=\s*\[([^\]]*)\]/s.exec(manifest);
  if (!declared) throw new Error("the workspace declares no gpui_platform features to publish");
  const features = [...declared[1].matchAll(/"([^"]+)"/g)].map((match) => match[1]);
  if (features.length === 0) throw new Error("gpui_platform's feature list came out empty");
  return features;
}

const buildInfo = {
  $comment: "Generated by script/generate-build-info.mjs from the workspace manifests. Do not edit.",
  version: field(workspace, "version"),
  repository: field(crate, "repository"),
  homepage: field(crate, "homepage"),
  license: field(workspace, "license"),
  // The features an application has to ask gpui_platform for, read from the
  // workspace rather than written down beside it: the install block the site
  // publishes is built from this, and a list typed into a script drifts. It
  // already had — `runtime_shaders` was in the manifest and not in the block.
  platformFeatures: platformFeatures(workspace),
  upstream: [
    {
      id: "gpui",
      label: "gpui",
      crate: "gpui-pre",
      repository: "https://crates.io/crates/gpui-pre",
      version: lockedVersion(lock, "gpui-pre"),
      note: "Zed's UI framework, published by GPUI Kit as a snapshot named gpui-pre.",
    },
    {
      id: "gpui-component",
      label: "gpui-component",
      crate: "gpui-component",
      repository: "https://crates.io/crates/gpui-component",
      version: lockedVersion(lock, "gpui-component"),
      note: "The upstream component library gpui-ai composes.",
    },
  ],
};

mkdirSync(OUTPUT, { recursive: true });
writeFileSync(join(OUTPUT, "build.json"), `${JSON.stringify(buildInfo, null, 2)}\n`);

process.stdout.write(
  `site/generated/build.json: v${buildInfo.version}, ` +
    `${buildInfo.upstream.map((pin) => `${pin.crate} ${pin.version}`).join(", ")}\n`,
);
